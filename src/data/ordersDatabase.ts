export function searchDatabaseOrders(query: string, filterType?: string): BaseOrder[] {
  return ORDERS_DATABASE.filter((ord) => {
    if (filterType && filterType !== 'TODOS') {
      if (ord.tipoNegocio.toUpperCase() !== filterType.toUpperCase()) {
        return false;
      }
    }
    if (!query.trim()) return true;
    const q = query.toLowerCase();
    return (
      ord.numPedido.toLowerCase().includes(q) ||
      ord.cliente.toLowerCase().includes(q) ||
      ord.geracao?.toLowerCase().includes(q) ||
      ord.modeloVariacao?.toLowerCase().includes(q) ||
      ord.corVariacao?.toLowerCase().includes(q) ||
      ord.mappedItemName.toLowerCase().includes(q) ||
      ord.comercial.toLowerCase().includes(q)
    );
  });
}
