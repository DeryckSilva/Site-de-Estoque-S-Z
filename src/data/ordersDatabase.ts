/**
 * Helper to detect which EquipmentItem in Mapeamento corresponds to the order's specifications
 */
export function autoDetectEquipmentItem(order: {
  geracao?: string;
  modeloVariacao?: string;
  corVariacao?: string;
  tipoItem?: string;
  operadora?: string;
}): { id: string; name: string } {
  const gen = (order.geracao || '').toLowerCase();
  const mod = (order.modeloVariacao || '').toLowerCase();
  const cor = (order.corVariacao || '').toLowerCase();
  const tipo = (order.tipoItem || '').toLowerCase();

  // 1. Smart Tags
  if (tipo.includes('tag') || gen.includes('tag') || mod.includes('tag') || cor.includes('tag')) {
    if (gen.includes('mini') || mod.includes('mini') || cor.includes('mini')) {
      return { id: 'tag-mini', name: 'TAG MINI' };
    }
    return { id: 'tag-card', name: 'TAG CARD' };
  }

  // 2. Rastreadores
  if (tipo.includes('rastreador') || gen.includes('lt-') || gen.includes('st-8') || gen.includes('st-3')) {
    if (gen.includes('lt-32 pro') || gen.includes('lt32 pro')) {
      return { id: 'lt-32-pro', name: 'LT-32 - PRO' };
    }
    if (gen.includes('lt-32') || gen.includes('lt32')) {
      return { id: 'lt-32', name: 'LT-32' };
    }
    if (gen.includes('8380')) {
      return { id: 'st-8380', name: 'ST-8380' };
    }
    if (gen.includes('8395')) {
      return { id: 'st-8395', name: 'ST-8395' };
    }
    if (gen.includes('8310') || gen.includes('8310um')) {
      return { id: 'st-8310-um', name: 'ST-8310 UM' };
    }
    if (gen.includes('340') || gen.includes('340ur')) {
      return { id: 'st-340-ur', name: 'ST-340 UR' };
    }
    if (gen.includes('310uc2')) {
      return { id: 'st-310-uc2', name: 'ST-310UC2' };
    }
    if (gen.includes('310') || gen.includes('310u')) {
      return { id: 'st-310-u', name: 'ST-310 U' };
    }
    if (gen.includes('sg-bras') || mod.includes('sg-bras') || cor.includes('sg bras')) {
      return { id: 'sg-bras', name: 'SG-BRAS' };
    }
    return { id: 'st-8380', name: 'ST-8380' };
  }

  // 3. Iscas 4G
  if (gen.includes('8410') || mod.includes('8410') || cor.includes('8410')) {
    return { id: 'st-8410', name: 'ST-8410' };
  }

  if (gen.includes('4g') || gen.includes('4410') || mod.includes('4g') || cor.includes('4g')) {
    if (mod.includes('3800') || cor.includes('3800') || mod.includes('dupla') || cor.includes('dupla')) {
      return { id: 'queck-4g-bat-3800', name: 'Queck (4G BAT 3.800)' };
    }
    if (mod.includes('s/bat') || mod.includes('sem bat')) {
      return { id: 'queck-4g-sbat', name: 'Queck (4G S/BAT)' };
    }
    if (mod.includes('dev') || cor.includes('dev') || mod.includes('reativação')) {
      return { id: '4g-dev', name: '4G (DEV)' };
    }
    // Default 4G models: ST4410G is mapped to queck-4g or st-8410
    return { id: 'st-8410', name: 'ST-8410' };
  }

  // 4. Iscas 2G
  if (gen.includes('2g') || gen.includes('410g') || mod.includes('2g')) {
    if (mod.includes('dev') || cor.includes('dev') || mod.includes('reativação') || mod.includes('reposição')) {
      return { id: '2g-dev', name: '2G (DEV)' };
    }
    if (mod.includes('s/bat') || mod.includes('sem bat')) {
      return { id: 'queck-2g-sbat', name: 'Queck (2G S/BAT)' };
    }
    return { id: 'queck-2g', name: 'Queck (2G)' };
  }

  // Fallback default
  return { id: 'st-8410', name: 'ST-8410' };
}

